CREATE EXTENSION IF NOT EXISTS citext;     -- courriels insensibles à la casse

-- ---------------------------------------------------------------------------------------------
-- 2. Rôles applicatifs (sans connexion : des utilisateurs LOGIN en héritent, voir db/README.md)
--    agri_app    : API, soumise à la sécurité au niveau des lignes (RLS)
--    agri_worker : pont MQTT et tâches périodiques, toutes organisations (BYPASSRLS)
-- ---------------------------------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'agri_app') THEN
        CREATE ROLE agri_app NOLOGIN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'agri_worker') THEN
        CREATE ROLE agri_worker NOLOGIN BYPASSRLS;
    END IF;
END
$$;

