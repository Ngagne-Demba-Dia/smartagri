CREATE TABLE IF NOT EXISTS farms (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    created_at timestamptz NOT NULL DEFAULT now(),
    organization_id uuid NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    name varchar(200) NOT NULL,
    region varchar(100),
    commune varchar(100),
    latitude double precision,
    longitude double precision,
    area_ha double precision,
    -- Colonne SQL seule (absente de l'ORM) : point PostGIS dérivé de latitude/longitude.
    location geometry(Point, 4326) GENERATED ALWAYS AS (
        CASE WHEN longitude IS NULL OR latitude IS NULL THEN NULL
             ELSE ST_SetSRID(ST_MakePoint(longitude, latitude), 4326) END
    ) STORED,
    CONSTRAINT ck_farms_latitude CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_farms_longitude CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);
CREATE INDEX IF NOT EXISTS ix_farms_organization_id ON farms (organization_id);
CREATE INDEX IF NOT EXISTS ix_farms_location ON farms USING gist (location);

CREATE TABLE IF NOT EXISTS fields (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    created_at timestamptz NOT NULL DEFAULT now(),
    organization_id uuid NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    farm_id uuid NOT NULL REFERENCES farms (id) ON DELETE CASCADE,
    name varchar(200) NOT NULL,
    area_ha double precision,
    soil_type varchar(50),
    irrigation_type varchar(20),
    -- GeoJSON Polygon validé par l'API (anneau fermé, lon/lat dans les bornes, ≤ 1000 sommets).
    geometry jsonb,
    -- Colonne SQL seule : géométrie PostGIS générée depuis le GeoJSON, indexée en GiST.
    geom geometry(Polygon, 4326) GENERATED ALWAYS AS (
        CASE WHEN geometry IS NULL THEN NULL
             ELSE ST_SetSRID(ST_GeomFromGeoJSON(geometry::text), 4326) END
    ) STORED,
    CONSTRAINT ck_fields_area CHECK (area_ha IS NULL OR area_ha > 0),
    CONSTRAINT ck_fields_irrigation CHECK (
        irrigation_type IS NULL OR irrigation_type IN ('drip', 'sprinkler', 'furrow', 'manual')),
    CONSTRAINT ck_fields_geometry_type CHECK (geometry IS NULL OR geometry ->> 'type' = 'Polygon')
);
CREATE INDEX IF NOT EXISTS ix_fields_organization_id ON fields (organization_id);
CREATE INDEX IF NOT EXISTS ix_fields_farm_id ON fields (farm_id);
CREATE INDEX IF NOT EXISTS ix_fields_geom ON fields USING gist (geom);

