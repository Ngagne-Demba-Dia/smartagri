-- ---------------------------------------------------------------------------------------------
-- 9. Journal d'audit en ajout seul
--    Seule modification tolérée : la mise à NULL de actor_user_id / organization_id par les
--    clés étrangères ON DELETE SET NULL (suppression d'un compte ou d'une organisation).
-- ---------------------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION audit_log_append_only() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE'
       AND (NEW.actor_user_id IS NOT DISTINCT FROM OLD.actor_user_id OR NEW.actor_user_id IS NULL)
       AND (NEW.organization_id IS NOT DISTINCT FROM OLD.organization_id OR NEW.organization_id IS NULL)
       AND (NEW.id, NEW.ts, NEW.action, NEW.target_type, NEW.target_id, NEW.ip, NEW.request_id)
           IS NOT DISTINCT FROM (OLD.id, OLD.ts, OLD.action, OLD.target_type, OLD.target_id, OLD.ip, OLD.request_id)
       AND NEW.details::text IS NOT DISTINCT FROM OLD.details::text THEN
        RETURN NEW;
    END IF;
    RAISE EXCEPTION 'audit_log est en ajout seul (% interdit)', TG_OP USING ERRCODE = 'insufficient_privilege';
END
$$;

DROP TRIGGER IF EXISTS audit_log_append_only ON audit_log;
CREATE TRIGGER audit_log_append_only BEFORE UPDATE OR DELETE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION audit_log_append_only();

-- ---------------------------------------------------------------------------------------------
-- 10. Sécurité au niveau des lignes (RLS)
--     L'API positionne `app.org_id` (UUID séparés par des virgules) à chaque transaction
--     (backend/app/db/session.py). Sans réglage, aucune ligne n'est visible.
--     RLS « ENABLE » et non « FORCE » : le propriétaire des tables (compte de migration) n'y est pas
--     soumis, ce qui permet à la fonction SECURITY DEFINER ci-dessous de résoudre une clé de kit.
--     L'API ne doit donc JAMAIS se connecter avec le compte propriétaire.
-- ---------------------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION app_current_org_ids() RETURNS uuid[]
LANGUAGE sql STABLE AS $$
    SELECT coalesce(string_to_array(nullif(current_setting('app.org_id', true), ''), ',')::uuid[], '{}'::uuid[])
$$;

DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['farms', 'fields', 'crop_cycles', 'devices', 'device_thresholds', 'alerts', 'images',
                             'diagnoses', 'recommendations', 'conversations']
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %I', t);
        EXECUTE format('CREATE POLICY tenant_isolation ON %I '
                       'USING (organization_id = ANY (app_current_org_ids())) '
                       'WITH CHECK (organization_id = ANY (app_current_org_ids()))', t);
    END LOOP;
END
$$;

-- Authentification X-Device-Key : organisation d'un kit actif à partir du HMAC de sa clé,
-- avant que `app.org_id` soit connu. Ne renvoie que l'UUID de l'organisation.
CREATE OR REPLACE FUNCTION app_device_org_by_key(key_hash text) RETURNS uuid
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public, pg_temp AS $$
    SELECT d.organization_id FROM devices AS d WHERE d.key_hash = $1 AND d.status = 'active'
$$;
REVOKE ALL ON FUNCTION app_device_org_by_key(text) FROM PUBLIC;

