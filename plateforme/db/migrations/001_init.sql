-- Agrégats continus (colonnes lues par backend/app/services/measurements.py).
CREATE MATERIALIZED VIEW IF NOT EXISTS measurements_1h
WITH (timescaledb.continuous, timescaledb.materialized_only = false) AS
SELECT
    device_id,
    time_bucket(INTERVAL '1 hour', ts) AS bucket,
    count(*)::integer AS n_points,
    avg(soil_moisture_pct) AS soil_moisture_pct_avg,
    min(soil_moisture_pct) AS soil_moisture_pct_min,
    max(soil_moisture_pct) AS soil_moisture_pct_max,
    avg(air_temp_c) AS air_temp_c_avg,
    min(air_temp_c) AS air_temp_c_min,
    max(air_temp_c) AS air_temp_c_max,
    avg(air_humidity_pct) AS air_humidity_pct_avg,
    avg(pressure_hpa) AS pressure_hpa_avg,
    avg(n_mgkg)::double precision AS n_mgkg_avg,
    avg(p_mgkg)::double precision AS p_mgkg_avg,
    avg(k_mgkg)::double precision AS k_mgkg_avg,
    avg(pump_on::integer)::double precision AS pump_on_ratio
FROM measurements
GROUP BY device_id, time_bucket(INTERVAL '1 hour', ts)
WITH NO DATA;

CREATE MATERIALIZED VIEW IF NOT EXISTS measurements_1d
WITH (timescaledb.continuous, timescaledb.materialized_only = false) AS
SELECT
    device_id,
    time_bucket(INTERVAL '1 day', ts) AS bucket,
    count(*)::integer AS n_points,
    avg(soil_moisture_pct) AS soil_moisture_pct_avg,
    min(soil_moisture_pct) AS soil_moisture_pct_min,
    max(soil_moisture_pct) AS soil_moisture_pct_max,
    avg(air_temp_c) AS air_temp_c_avg,
    min(air_temp_c) AS air_temp_c_min,
    max(air_temp_c) AS air_temp_c_max,
    avg(air_humidity_pct) AS air_humidity_pct_avg,
    avg(pressure_hpa) AS pressure_hpa_avg,
    avg(n_mgkg)::double precision AS n_mgkg_avg,
    avg(p_mgkg)::double precision AS p_mgkg_avg,
    avg(k_mgkg)::double precision AS k_mgkg_avg,
    avg(pump_on::integer)::double precision AS pump_on_ratio
FROM measurements
GROUP BY device_id, time_bucket(INTERVAL '1 day', ts)
WITH NO DATA;

