CREATE TABLE IF NOT EXISTS devices (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    created_at timestamptz NOT NULL DEFAULT now(),
    organization_id uuid NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    field_id uuid REFERENCES fields (id) ON DELETE SET NULL,
    serial varchar(11) NOT NULL,
    name varchar(200),
    firmware_version varchar(32),
    -- HMAC-SHA256 (poivré) de la clé du kit ; la clé en clair n'est jamais stockée.
    key_hash varchar(64) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'active',
    last_seen_at timestamptz,
    CONSTRAINT uq_devices_serial UNIQUE (serial),
    CONSTRAINT uq_devices_key_hash UNIQUE (key_hash),
    CONSTRAINT ck_devices_serial_format CHECK (serial ~ '^SA92-[0-9]{6}$'),
    CONSTRAINT ck_devices_status CHECK (status IN ('active', 'inactive', 'retired'))
);
CREATE INDEX IF NOT EXISTS ix_devices_organization_id ON devices (organization_id);
CREATE INDEX IF NOT EXISTS ix_devices_field_id ON devices (field_id);

CREATE TABLE IF NOT EXISTS device_thresholds (
    device_id uuid PRIMARY KEY REFERENCES devices (id) ON DELETE CASCADE,
    organization_id uuid NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    desired_start_pct integer NOT NULL,
    desired_stop_pct integer NOT NULL,
    reported_start_pct integer,
    reported_stop_pct integer,
    sync_status varchar(10) NOT NULL DEFAULT 'pending',
    command_id uuid,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by uuid REFERENCES users (id) ON DELETE SET NULL,
    -- Règle firmware v1.1 : 0 ≤ start, start + 5 ≤ stop ≤ 100 (entiers).
    CONSTRAINT ck_device_thresholds_desired_rule CHECK (
        desired_start_pct >= 0 AND desired_start_pct + 5 <= desired_stop_pct AND desired_stop_pct <= 100),
    CONSTRAINT ck_device_thresholds_sync_status CHECK (sync_status IN ('pending', 'sent', 'applied', 'failed'))
);
CREATE INDEX IF NOT EXISTS ix_device_thresholds_organization_id ON device_thresholds (organization_id);
CREATE INDEX IF NOT EXISTS ix_device_thresholds_command_id ON device_thresholds (command_id);
CREATE INDEX IF NOT EXISTS ix_device_thresholds_pending ON device_thresholds (sync_status)
    WHERE sync_status = 'pending';

