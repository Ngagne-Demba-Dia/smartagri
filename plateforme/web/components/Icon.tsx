export type IconName = keyof typeof ICONS;

export function Icon({ name, size = 20, label }: { name: IconName; size?: number; label?: string }) {
  const Glyph = ICONS[name];
  return (
    <Glyph
      size={size}
      strokeWidth={2}
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      focusable="false"
    />
  );
}
